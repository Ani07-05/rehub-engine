"""Copies compose.yml into the heredoc in scripts/install.sh. Run after editing compose.yml."""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BEGIN = "# BEGIN COMPOSE (generated by scripts/embed-compose.py, do not edit)\n"
END = "# END COMPOSE\n"


def main() -> None:
    script = ROOT / "scripts" / "install.sh"
    text = script.read_text()
    compose = (ROOT / "compose.yml").read_text()
    block = f"{BEGIN}emit_compose() {{\n  cat <<'COMPOSE_EOF'\n{compose}COMPOSE_EOF\n}}\n{END}"
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if not pattern.search(text):
        raise SystemExit("markers not found in install.sh")
    script.write_text(pattern.sub(lambda _m: block, text))


if __name__ == "__main__":
    main()
